const dictionaries: Record<AppLanguage, Record<TranslationKey, string>> = { fr, en, es }

export { LANGUAGE_OPTIONS }
export type { AppLanguage }

export function currentLanguage(): AppLanguage {
  return settingsStore.language.value
}

export function t(key: TranslationKey, vars: Record<string, string | number> = {}): string {
  const lang = settingsStore.language.value || DEFAULT_LANGUAGE
  const template = dictionaries[lang]?.[key] ?? dictionaries[DEFAULT_LANGUAGE][key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`))
}
